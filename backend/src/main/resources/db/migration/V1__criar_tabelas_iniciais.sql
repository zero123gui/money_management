-- Modelo de dados do MVP (docs/DECISOES.md, "Modelo de dados (MVP)").
-- Migração aplicada nunca é editada: correções entram em uma nova versão.

CREATE TABLE usuario (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(100) NOT NULL,
    email              VARCHAR(254) NOT NULL,
    -- Hash BCrypt (60 caracteres); a senha em texto puro nunca é gravada.
    senha_hash         VARCHAR(100) NOT NULL,
    compartilha_resumo BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- E-mail é o login: "Ana@x.com" e "ana@x.com" são o mesmo usuário.
CREATE UNIQUE INDEX uk_usuario_email ON usuario (lower(email));

CREATE TABLE categoria (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(50) NOT NULL,
    tipo       VARCHAR(7)  NOT NULL,
    -- Nulo = categoria padrão do sistema, visível a todos.
    usuario_id BIGINT      REFERENCES usuario (id) ON DELETE CASCADE,
    ativa      BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_categoria_tipo CHECK (tipo IN ('RECEITA', 'DESPESA')),
    -- Alvo da chave estrangeira composta de lancamento (garante o mesmo tipo).
    CONSTRAINT uk_categoria_id_tipo UNIQUE (id, tipo)
);

-- Mesmo nome e tipo não se repetem para o mesmo dono, sem diferenciar
-- maiúsculas. O COALESCE agrupa as padrão, pois NULL nunca é igual a NULL.
CREATE UNIQUE INDEX uk_categoria_dono_nome_tipo
    ON categoria (COALESCE(usuario_id, 0), lower(nome), tipo);

CREATE TABLE lancamento (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT        NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    tipo          VARCHAR(7)    NOT NULL,
    valor         NUMERIC(15,2) NOT NULL,
    data          DATE          NOT NULL,
    categoria_id  BIGINT        NOT NULL,
    descricao     VARCHAR(255),
    -- Nulo = ativo; preenchido = excluído logicamente (RF-09, RF-24).
    excluido_em   TIMESTAMPTZ,
    criado_em     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_lancamento_tipo CHECK (tipo IN ('RECEITA', 'DESPESA')),
    -- O tipo diz se entra ou sai; o valor é sempre positivo.
    CONSTRAINT ck_lancamento_valor_positivo CHECK (valor > 0),
    -- Impede, no próprio banco, um lançamento de receita numa categoria de despesa.
    -- Sem ON DELETE: ao excluir a conta, as duas cascatas a partir de usuario
    -- rodam no mesmo comando, e o NO ACTION só é conferido no fim dele.
    CONSTRAINT fk_lancamento_categoria FOREIGN KEY (categoria_id, tipo)
        REFERENCES categoria (id, tipo)
);

-- Listagem e relatórios: lançamentos ativos do usuário por data (RF-10, RF-16, RF-17).
CREATE INDEX ix_lancamento_ativos
    ON lancamento (usuario_id, data DESC)
    WHERE excluido_em IS NULL;

-- Lista de excluídos, do mais recente para o mais antigo (RF-24).
CREATE INDEX ix_lancamento_excluidos
    ON lancamento (usuario_id, excluido_em DESC)
    WHERE excluido_em IS NOT NULL;

CREATE INDEX ix_lancamento_categoria ON lancamento (categoria_id);

